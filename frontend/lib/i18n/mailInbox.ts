const DICT: Record<AppLanguage, Record<Key, string>> = { es, en, fr, it, pt };
export type MailKey = Key;

export function mailText(language: AppLanguage, key: Key, vars?: Record<string, string | number>): string {
  let text = (DICT[language] ?? es)[key] ?? es[key];
  for (const [name, value] of Object.entries(vars ?? {})) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}

function lookup(language: AppLanguage, prefix: "c_" | "p_" | "f_", raw: string, fallback: Key): string {
  const key = `${prefix}${String(raw || "").trim().toLowerCase()}` as Key;
  return key in es ? mailText(language, key) : mailText(language, fallback);
}

export const mailCategoryLabel = (l: AppLanguage, raw: string) => lookup(l, "c_", raw, "c_other");
export const mailPriorityLabel = (l: AppLanguage, raw: string) => lookup(l, "p_", raw, "p_other");
export const mailFilterLabel = (l: AppLanguage, raw: string) => lookup(l, "f_", raw, "c_other");
