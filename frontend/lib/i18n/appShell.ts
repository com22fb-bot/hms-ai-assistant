const DICT: Record<AppLanguage, Record<Key, string>> = { es, en, fr, it, pt };
export type ShellKey = Key;
export function shellText(language: AppLanguage, key: Key, vars?: Record<string, string>): string {
  let text = (DICT[language] ?? es)[key] ?? es[key];
  for (const [name, value] of Object.entries(vars ?? {})) text = text.replaceAll(`{${name}}`, value);
  return text;
}
