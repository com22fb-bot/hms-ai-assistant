const DICT: Record<AppLanguage, Record<Key, string>> = { es, en, fr, it, pt };

export type ImportKey = Key;

export function importText(
  language: AppLanguage,
  key: Key,
  vars?: Record<string, string | number>,
): string {
  let text = (DICT[language] ?? es)[key] ?? es[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

/** Etiqueta traducida para una llave de categoría/triage del backend; nunca devuelve la llave cruda. */
export function importCategoryLabel(language: AppLanguage, raw: string): string {
  const key = `c_${String(raw || "").trim().toLowerCase()}` as Key;
  return key in es ? importText(language, key) : importText(language, "c_other");
}
