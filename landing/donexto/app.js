let lang = "es";

function applyLang() {
  const dict = strings[lang];
  document.documentElement.lang = lang === "es" ? "es" : "en";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (!key || dict[key] == null) return;
    if (key === "hero_title" || key === "n3_badge") {
      el.innerHTML = dict[key];
    } else {
      el.textContent = dict[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key && dict[key] != null) el.setAttribute("placeholder", dict[key]);
  });

  const toggle = document.getElementById("langToggle");
  if (toggle) toggle.textContent = lang === "es" ? "EN" : "ES";

  document.querySelectorAll('a[href^="mailto"]').forEach((mailBtn) => {
    if (mailBtn.classList.contains("btn") || mailBtn.closest(".foot-mail")) {
      const isCta =
        mailBtn.classList.contains("ghost") ||
        mailBtn.getAttribute("data-i18n") === "cta_mail";
      if (isCta) {
        mailBtn.setAttribute(
          "href",
          lang === "es"
            ? "mailto:hola@donexto.com?subject=Donexto%20contacto"
            : "mailto:hello@donexto.com?subject=Donexto%20contact",
        );
      }
    }
  });
}

document.getElementById("langToggle")?.addEventListener("click", () => {
  lang = lang === "es" ? "en" : "es";
  applyLang();
});

document.getElementById("year").textContent = String(new Date().getFullYear());

document.getElementById("waitForm")?.addEventListener("submit", (event) => {
  event.preventDefault();
  const form = event.currentTarget;
  const status = document.getElementById("formStatus");
  const dict = strings[lang];
  const data = new FormData(form);
  const name = String(data.get("name") || "").trim();
  const email = String(data.get("email") || "").trim().toLowerCase();
  const country = String(data.get("country") || "MX");

  if (!email.includes("@") || email.length < 5) {
    status.hidden = false;
    status.textContent = dict.form_err;
    status.style.background = "rgba(140, 40, 28, 0.28)";
    status.style.color = "#ffb4a8";
    return;
  }

  const to = lang === "es" ? "hola@donexto.com" : "hello@donexto.com";
  const subject = encodeURIComponent("Donexto contact / waitlist");
  const body = encodeURIComponent(
    [
      "Donexto landing contact",
      "",
      `Name: ${name || "(not provided)"}`,
      `Email: ${email}`,
      `Country: ${country}`,
      `Lang: ${lang}`,
      `Source: donexto.com`,
    ].join("\n"),
  );

  status.hidden = false;
  status.textContent = dict.form_ok;
  status.style.background = "rgba(12, 138, 128, 0.2)";
  status.style.color = "#9fe0c8";

  window.location.href = `mailto:${to}?subject=${subject}&body=${body}`;
});

applyLang();
